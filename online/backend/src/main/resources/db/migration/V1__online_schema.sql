CREATE TABLE users (
    id UUID PRIMARY KEY,
    display_name VARCHAR(60) NOT NULL,
    username VARCHAR(24) NOT NULL UNIQUE CHECK (username = lower(username)),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (email = lower(email)),
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    normalized_name VARCHAR(200) NOT NULL UNIQUE,
    parent_id BIGINT REFERENCES categories(id)
);
CREATE TABLE questions (
    id UUID PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    text TEXT NOT NULL,
    correct_answer TEXT NOT NULL,
    incorrect_answers TEXT NOT NULL,
    difficulty VARCHAR(10) NOT NULL CHECK (difficulty IN ('easy', 'medium', 'hard')),
    question_type VARCHAR(20) NOT NULL CHECK (question_type IN ('MULTIPLE_CHOICE', 'TRUE_FALSE')),
    external_id VARCHAR(80) NOT NULL UNIQUE,
    content_key VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_questions_filters ON questions(category_id, difficulty, question_type);
CREATE TABLE quiz_rooms (
    id UUID PRIMARY KEY,
    code VARCHAR(8) NOT NULL UNIQUE,
    host_id UUID NOT NULL REFERENCES users(id),
    title VARCHAR(80) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'LOBBY' CHECK (status IN ('LOBBY','QUESTION','REVEAL','FINISHED','CLOSED')),
    category_id BIGINT REFERENCES categories(id),
    difficulty VARCHAR(10) NOT NULL,
    question_type VARCHAR(20) NOT NULL,
    question_count INTEGER NOT NULL CHECK (question_count BETWEEN 1 AND 50),
    seconds_per_question INTEGER NOT NULL CHECK (seconds_per_question BETWEEN 5 AND 120),
    max_players INTEGER NOT NULL CHECK (max_players BETWEEN 2 AND 50),
    password_hash VARCHAR(100),
    current_question INTEGER NOT NULL DEFAULT -1,
    deadline TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_rooms_host ON quiz_rooms(host_id, created_at);
CREATE INDEX ix_rooms_deadline ON quiz_rooms(status, deadline);
CREATE TABLE room_participants (
    room_id UUID NOT NULL REFERENCES quiz_rooms(id),
    user_id UUID NOT NULL REFERENCES users(id),
    role VARCHAR(8) NOT NULL CHECK (role IN ('HOST','PLAYER')),
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL,
    left_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY(room_id, user_id)
);
CREATE INDEX ix_participants_user ON room_participants(user_id);
CREATE TABLE game_sessions (
    id UUID PRIMARY KEY,
    room_id UUID NOT NULL UNIQUE REFERENCES quiz_rooms(id),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE room_questions (
    id UUID PRIMARY KEY,
    room_id UUID NOT NULL REFERENCES quiz_rooms(id),
    question_id UUID NOT NULL REFERENCES questions(id),
    ordinal INTEGER NOT NULL,
    text TEXT NOT NULL,
    correct_answer TEXT NOT NULL,
    choices TEXT NOT NULL,
    difficulty VARCHAR(10) NOT NULL,
    question_type VARCHAR(20) NOT NULL,
    points INTEGER NOT NULL CHECK(points IN (5, 10)),
    UNIQUE(room_id, ordinal), UNIQUE(room_id, question_id)
);
CREATE TABLE answers (
    id UUID PRIMARY KEY,
    room_question_id UUID NOT NULL REFERENCES room_questions(id),
    user_id UUID NOT NULL REFERENCES users(id),
    selected_index INTEGER NOT NULL CHECK(selected_index >= 0),
    is_correct BOOLEAN NOT NULL,
    points INTEGER NOT NULL CHECK(points IN (0, 5, 10)),
    answered_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(room_question_id, user_id)
);
CREATE INDEX ix_answers_user ON answers(user_id);
CREATE TABLE scores (
    session_id UUID NOT NULL REFERENCES game_sessions(id),
    user_id UUID NOT NULL REFERENCES users(id),
    points INTEGER NOT NULL DEFAULT 0 CHECK(points >= 0),
    correct_count INTEGER NOT NULL DEFAULT 0 CHECK(correct_count >= 0),
    PRIMARY KEY(session_id, user_id)
);
CREATE INDEX ix_scores_user ON scores(user_id);
CREATE TABLE question_bank_imports (
    id UUID PRIMARY KEY,
    user_id UUID REFERENCES users(id),
    source VARCHAR(100) NOT NULL,
    received_count INTEGER NOT NULL,
    inserted_count INTEGER NOT NULL,
    imported_at TIMESTAMP WITH TIME ZONE NOT NULL
);
